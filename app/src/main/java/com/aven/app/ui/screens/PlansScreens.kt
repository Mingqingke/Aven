@Composable
fun PlansScreen() {
    val c = LocalAven.current
    val goals by Store.goals.collectAsState()
    val tasks by Store.tasks.collectAsState()
    val plans by Store.plans.collectAsState()
    val exams by Store.exams.collectAsState()
    val scope = rememberCoroutineScope()
    val context = LocalContext.current

    var tab by remember { mutableStateOf(0) }
    var showGoal by remember { mutableStateOf(false) }
    var editGoal by remember { mutableStateOf<GoalEntity?>(null) }
    var showTask by remember { mutableStateOf(false) }
    var editTask by remember { mutableStateOf<TaskEntity?>(null) }
    var showPlan by remember { mutableStateOf(false) }
    var deleteGoal by remember { mutableStateOf<GoalEntity?>(null) }
    var aiBusy by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<List<TaskEntity>?>(null) }

    val pending = tasks.filter { it.status == 0 || it.status == 3 }
    val done = tasks.filter { it.status == 1 }

    Column(Modifier.fillMaxWidth()) {
        ScreenTitle("学习计划", "目标 → 阶段 → 任务 → 复盘") {
            Box(
                Modifier.size(38.dp).clip(CircleShape).background(c.ink).clickable { showTask = true },
                contentAlignment = Alignment.Center,
            ) { Icon(MiuixIcons.Add, "新建任务", Modifier.size(19.dp), tint = c.card) }
        }
        TabRow(
            tabs = listOf("任务", "目标", "阶段"),
            selectedTabIndex = tab,
            onTabSelected = { tab = it },
            modifier = Modifier.fillMaxWidth().padding(horizontal = 16.dp),
        )
        AnimatedContent(
            targetState = tab,
            modifier = Modifier.weight(1f),
            transitionSpec = { fadeIn(tween(200)) togetherWith fadeOut(tween(100)) },
            label = "planTab",
        ) { current ->
        when (current) {
            0 -> TasksTab(pending, done, onToggle = { task ->
                scope.launch {
                    Store.updateTask(
                        task.copy(
                            status = if (task.status == 1) 0 else 1,
                            doneAt = if (task.status == 1) 0L else System.currentTimeMillis(),
                        )
                    )
                }
            }, onEdit = { editTask = it }, onAdd = { showTask = true })
            1 -> GoalsTab(goals, exams, onAdd = { editGoal = null; showGoal = true }, onEdit = { editGoal = it; showGoal = true }, onDelete = { deleteGoal = it },
                onAiPlan = { goal ->
                    if (!Ai.hasKey(context)) {
                        AppState.say("请先在设置中配置 DeepSeek API Key")
                    } else if (!Prefs.aiConsent.value) {
                        AppState.say("请先在 AI 分析页同意发送学业数据")
                    } else {
                        scope.launch {
                            aiBusy = true
                            val digest = exams.sortedByDescending { it.date }.take(5).joinToString("\n") {
                                "${it.title}：总分 ${ScoreEngine.fmtScore(it.rawTotal)}/${ScoreEngine.fmtScore(it.fullTotal)}，" +
                                    it.subjects.joinToString("、") { s -> "${s.subject}${ScoreEngine.fmtScore(s.raw)}" }
                            }
                            val prompt = """请根据下面的目标与成绩，拆解成 6-10 条可以在两周内执行的学习任务。
只输出 JSON：{"tasks":[{"title":"任务","subject":"学科","minutes":40,"priority":0,"days":3}]}
priority 取 0/1/2，days 表示几天内完成。不要输出其他内容。

目标：${goal.subject.ifBlank { "总分" }} ${ScoreEngine.fmtScore(goal.targetScore)} 分${if (goal.examDate > 0) "，考试日期 ${Dates.fmt(goal.examDate)}" else ""}
成绩：
$digest"""
                            when (val r = Ai.chat(context, listOf("system" to "你是学习计划助手，只输出 JSON。", "user" to prompt), jsonMode = true, maxTokens = 1500)) {
                                is Ai.Out.Ok -> {
                                    val list = runCatching {
                                        val json = r.text.substringAfter('{', "").let { if (it.isBlank()) r.text else "{$it" }
                                        val arr = JSONObject(json).optJSONArray("tasks") ?: JSONArray()
                                        (0 until arr.length()).mapNotNull { i ->
                                            val o = arr.optJSONObject(i) ?: return@mapNotNull null
                                            val title = o.optString("title").trim()
                                            if (title.isBlank()) null else TaskEntity(
                                                subject = o.optString("subject"),
                                                title = title,
                                                estimateMin = o.optInt("minutes", 30),
                                                priority = o.optInt("priority", 1).coerceIn(0, 2),
                                                dueDate = System.currentTimeMillis() + o.optInt("days", 7).coerceIn(1, 30) * 86_400_000L,
                                            )
                                        }
                                    }.getOrDefault(emptyList())
                                    if (list.isEmpty()) AppState.say("AI 没有返回可用的任务") else generated = list
                                }
                                is Ai.Out.Err -> AppState.say(r.message)
                            }
                            aiBusy = false
                        }
                    }
                })
            else -> PlansTab(plans, tasks, onAdd = { showPlan = true }, onDelete = { plan ->
                scope.launch { Store.deletePlan(plan.id); AppState.say("阶段计划已删除") }
            })
        }
        }
    }

    if (showGoal) {
        GoalDialog(exams = exams, existing = editGoal, onClose = { showGoal = false }) { goal ->
            scope.launch {
                if (goal.id == 0L) Store.addGoal(goal) else Store.updateGoal(goal)
                showGoal = false
                AppState.say("目标已保存")
            }
        }
    }

    if (deleteGoal != null) {
        OverlayDialog(
            show = true, title = "删除这个目标", summary = "不影响已有成绩",
            onDismissRequest = { deleteGoal = null },
        ) {
            Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                SoftButton("取消", { deleteGoal = null }, modifier = Modifier.weight(1f))
                PrimaryButton("删除", {
                    scope.launch { Store.deleteGoal(deleteGoal!!.id); deleteGoal = null }
                }, modifier = Modifier.weight(1f))
            }
        }
    }

    if (showTask) {
        TaskDialog(existing = editTask, onClose = { showTask = false; editTask = null }) { task ->
            scope.launch {
                if (task.id == 0L) Store.addTask(task) else Store.updateTask(task)
                showTask = false
                editTask = null
                AppState.say("任务已保存")
            }
        }
    } else if (editTask != null) {
        TaskDialog(existing = editTask, onClose = { editTask = null }) { task ->
            scope.launch {
                Store.updateTask(task)
                editTask = null
                AppState.say("任务已更新")
            }
        }
    }

    if (showPlan) {
        PlanDialog(onClose = { showPlan = false }) { plan ->
            scope.launch {
                Store.addPlan(plan)
                showPlan = false
                AppState.say("阶段计划已创建")
            }
        }
    }

    generated?.let { list ->
        OverlayDialog(
            show = true, title = "AI 生成的 ${list.size} 个任务",
            summary = "加入后仍可修改或删除",
            onDismissRequest = { generated = null },
        ) {
            Column(Modifier.fillMaxWidth().heightIn(max = 420.dp).verticalScroll(rememberScrollState())) {
                list.take(6).forEach { t ->
                    Row(Modifier.fillMaxWidth().padding(vertical = 4.dp)) {
                        Text("·", fontSize = 12.sp, color = c.secondary)
                        Spacer(Modifier.width(6.dp))
                        Text(
                            "${t.title} ${t.subject.ifBlank { "综合" }} ${t.estimateMin} 分钟",
                            fontSize = 11.5.sp, color = c.ink, lineHeight = 17.sp,
                        )
                    }
                }
                if (list.size > 6) Text("另有 ${list.size - 6} 个任务", fontSize = 10.5.sp, color = c.secondary)
                Spacer(Modifier.height(12.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                    SoftButton("取消", { generated = null }, modifier = Modifier.weight(1f))
                    PrimaryButton("加入任务", {
                        scope.launch {
                            Store.addTasks(list)
                            generated = null
                            AppState.say("已加入 ${list.size} 个任务")
                        }
                    }, modifier = Modifier.weight(1f))
                }
            }
        }
    }

    if (aiBusy) {
        OverlayDialog(show = true, title = "正在拆解计划", summary = "结合目标与最近成绩生成任务", onDismissRequest = {}) {
            Text("可能需要十几秒", fontSize = 11.sp, color = c.secondary)
        }
    }
}

@Composable
private fun TasksTab(
    pending: List<TaskEntity>,
    done: List<TaskEntity>,
    onToggle: (TaskEntity) -> Unit,
    onEdit: (TaskEntity) -> Unit,
    onAdd: () -> Unit,
) {
    val c = LocalAven.current
    LazyColumn(
        Modifier.fillMaxWidth(),
        contentPadding = PaddingValues(start = 16.dp, end = 16.dp, top = 12.dp, bottom = 120.dp),
    ) {
        if (pending.isEmpty() && done.isEmpty()) {
            item {
                EmptyState(
                    MiuixIcons.Tasks, "还没有学习任务",
                    "把目标拆成今天能完成的小事",
                    "新建任务", onAdd,
                )
            }
        } else {
            item {
                val today = Dates.today()
                val todayTasks = pending.filter { it.dueDate == 0L || it.dueDate <= today + 86_400_000L - 1 }
                SectionLabel("待完成", trailing = "${pending.size} 项", accent = c.blue)
                BoxCard(insidePadding = 0.dp) {
                    if (pending.isEmpty()) {
                        Text("全部完成了", fontSize = 12.5.sp, color = c.secondary, modifier = Modifier.padding(16.dp))
                    } else {
                        pending.forEachIndexed { i, t ->
                            TaskRowFull(t, overdue = t.dueDate in 1..(today - 1), onToggle = { onToggle(t) }, onEdit = { onEdit(t) })
                            if (i < pending.lastIndex) Divider(startPadding = 52.dp)
                        }
                    }
                }
                if (todayTasks.isNotEmpty()) {
                    Spacer(Modifier.height(6.dp))
                    Text("今天有 ${todayTasks.size} 项需要推进", fontSize = 10.5.sp, color = c.secondary, modifier = Modifier.padding(start = 6.dp))
                }
            }
            item {
                val week = weekCompletion(done)
                SectionLabel("本周复盘", accent = c.positive)
                BoxCard {
                    Text("任务完成情况", fontSize = 12.5.sp, color = c.ink)
                    Spacer(Modifier.height(12.dp))
                    WeekBars(week.map { it.second }, listOf("一", "二", "三", "四", "五", "六", "日"), c.positive)
                    Spacer(Modifier.height(10.dp))
                    Text(
                        "已完成 ${done.size} 项 共 ${done.size + pending.size} 项",
                        fontSize = 10.5.sp, color = c.secondary, lineHeight = 15.sp,
                    )
                }
            }
            if (done.isNotEmpty()) {
                item { SectionLabel("已完成", trailing = "${done.size} 项", accent = c.secondary) }
                item {
                    BoxCard(insidePadding = 0.dp) {
                        done.take(8).forEachIndexed { i, t ->
                            TaskRowFull(t, overdue = false, onToggle = { onToggle(t) }, onEdit = { onEdit(t) })
                            if (i < minOf(done.size, 8) - 1) Divider(startPadding = 52.dp)
                        }
                    }
                }
            }
        }
    }
}

private fun weekCompletion(done: List<TaskEntity>): List<Pair<Int, Float>> {
    val today = Dates.date(System.currentTimeMillis())
    val monday = today.minusDays((today.dayOfWeek.value - 1).toLong())
    return (0..6).map { i ->
        val day = monday.plusDays(i.toLong())
        val total = done.count { it.doneAt > 0 && Dates.date(it.doneAt) == day }
        i to if (total == 0) 0f else (total / 3f).coerceAtMost(1f)
    }
}

@Composable
private fun TaskRowFull(task: TaskEntity, overdue: Boolean, onToggle: () -> Unit, onEdit: () -> Unit) {
    val c = LocalAven.current
    val done = task.status == 1
    Row(
        Modifier.fillMaxWidth().clickable(onClick = onEdit).padding(horizontal = 14.dp, vertical = 12.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Box(
            Modifier.size(22.dp).clip(CircleShape)
                .background(if (done) c.positive else c.neutralBg)
                .clickable(onClick = onToggle),
            contentAlignment = Alignment.Center,
        ) {
            if (done) Icon(MiuixIcons.Ok, null, Modifier.size(13.dp), tint = c.card)
        }
        Spacer(Modifier.width(14.dp))
        Column(Modifier.weight(1f)) {
            Text(
                task.title, fontSize = 13.5.sp,
                color = if (done) c.secondary else c.ink,
                textDecoration = if (done) TextDecoration.LineThrough else null,
                maxLines = 2, overflow = TextOverflow.Ellipsis,
            )
            Spacer(Modifier.height(2.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                if (task.subject.isNotBlank()) {
                    Text(task.subject, fontSize = 10.sp, color = c.secondary)
                    Text("  ", fontSize = 10.sp, color = c.secondary)
                }
                Text(
                    when {
                        task.status == 2 -> "已跳过"
                        task.status == 3 -> "已延期"
                        task.dueDate > 0 -> Dates.fmt(task.dueDate) + if (overdue) "  已逾期" else ""
                        else -> "未设截止"
                    },
                    fontSize = 10.sp, color = if (overdue) c.negative else c.secondary,
                )
            }
        }
        if (task.priority == 2) Badge("优先", c.negative, c.negative.copy(alpha = 0.10f))
        else if (task.priority == 0) Badge("低", c.secondary, c.neutralBg)
    }
}

@Composable
private fun GoalsTab(
    goals: List<GoalEntity>,
    exams: List<com.aven.app.core.calc.ExamSnap>,
    onAdd: () -> Unit,
    onEdit: (GoalEntity) -> Unit,
    onDelete: (GoalEntity) -> Unit,
    onAiPlan: (GoalEntity) -> Unit,
) {
    val c = LocalAven.current
    val latest = exams.maxByOrNull { it.date }
    LazyColumn(
        Modifier.fillMaxWidth(),
        contentPadding = PaddingValues(start = 16.dp, end = 16.dp, top = 12.dp, bottom = 120.dp),
    ) {
        if (goals.isEmpty()) {
            item {
                EmptyState(
                    MiuixIcons.Add, "还没有设定目标",
                    "目标可以是总分或单科 差距按真实成绩计算",
                    "设定目标", onAdd,
                )
            }
        } else {
            items(goals) { g ->
                val current = if (g.subject.isBlank()) latest?.rawTotal else latest?.subject(g.subject)?.raw
                val progress = ScoreEngine.goalProgress(current, g.targetScore)
                BoxCard(modifier = Modifier.padding(bottom = 10.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Column(Modifier.weight(1f)) {
                            Text(
                                (g.subject.ifBlank { "总分" }) + "目标",
                                fontSize = 14.5.sp, fontWeight = FontWeight.Medium, color = c.ink,
                            )
                            Spacer(Modifier.height(3.dp))
                            Text(
                                "当前 ${current?.let { ScoreEngine.fmtScore(it) } ?: "—"}  目标 ${ScoreEngine.fmtScore(g.targetScore)}",
                                fontSize = 11.sp, color = c.secondary,
                            )
                        }
                        Text("${(progress * 100).toInt()}%", fontSize = 16.sp, fontWeight = FontWeight.SemiBold, color = c.ink)
                    }
                    Spacer(Modifier.height(10.dp))
                    RateBar(progress, c.positive, height = 7.dp)
                    Spacer(Modifier.height(10.dp))
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        if (g.examDate > 0) {
                            Badge("${Dates.fmt(g.examDate)}  ${Dates.daysBetween(System.currentTimeMillis(), g.examDate)} 天", c.secondary, c.neutralBg)
                        }
                        Spacer(Modifier.weight(1f))
                        Text("AI 拆解", fontSize = 11.sp, color = c.blue, modifier = Modifier.clickable { onAiPlan(g) })
                        Spacer(Modifier.width(12.dp))
                        Text("编辑", fontSize = 11.sp, color = c.secondary, modifier = Modifier.clickable { onEdit(g) })
                        Spacer(Modifier.width(12.dp))
                        Icon(MiuixIcons.Delete, "删除", Modifier.size(15.dp).clickable { onDelete(g) }, tint = c.secondary)
                    }
                }
            }
            item {
                SoftButton("新增目标", onAdd, modifier = Modifier.fillMaxWidth())
            }
        }
    }
}

@Composable
private fun PlansTab(
    plans: List<PlanEntity>,
    tasks: List<TaskEntity>,
    onAdd: () -> Unit,
    onDelete: (PlanEntity) -> Unit,
) {
    val c = LocalAven.current
    LazyColumn(
        Modifier.fillMaxWidth(),
        contentPadding = PaddingValues(start = 16.dp, end = 16.dp, top = 12.dp, bottom = 120.dp),
    ) {
        if (plans.isEmpty()) {
            item {
                EmptyState(
                    MiuixIcons.Tasks, "还没有阶段计划",
                    "把目标拆成阶段内的几件事",
                    "新建阶段计划", onAdd,
                )
            }
        } else {
            items(plans) { p ->
                val related = tasks.filter { it.planId == p.id }
                val done = related.count { it.status == 1 }
                BoxCard(modifier = Modifier.padding(bottom = 10.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Column(Modifier.weight(1f)) {
                            Text(p.title, fontSize = 14.5.sp, fontWeight = FontWeight.Medium, color = c.ink)
                            Spacer(Modifier.height(3.dp))
                            Text(
                                listOfNotNull(
                                    p.subject.takeIf { it.isNotBlank() },
                                    p.stageName.takeIf { it.isNotBlank() },
                                    if (p.startDate > 0) "${Dates.fmtShort(p.startDate)} - ${Dates.fmtShort(p.endDate)}" else null,
                                ).joinToString("  ").ifBlank { "未设置时间" },
                                fontSize = 10.5.sp, color = c.secondary,
                            )
                        }
                        Icon(MiuixIcons.Delete, "删除", Modifier.size(16.dp).clickable { onDelete(p) }, tint = c.secondary)
                    }
                    Spacer(Modifier.height(10.dp))
                    RateBar(if (related.isEmpty()) 0f else done.toFloat() / related.size, c.ink, height = 6.dp)
                    Spacer(Modifier.height(6.dp))
                    Text(
                        if (related.isEmpty()) "还没有关联任务" else "$done / ${related.size} 个任务完成",
                        fontSize = 10.sp, color = c.secondary,
                    )
                }
            }
            item { SoftButton("新建阶段计划", onAdd, modifier = Modifier.fillMaxWidth()) }
        }
    }
}

@Composable
private fun GoalDialog(
    exams: List<com.aven.app.core.calc.ExamSnap>,
    existing: GoalEntity?,
    onClose: () -> Unit,
    onSave: (GoalEntity) -> Unit,
) {
    val c = LocalAven.current
    val subjects = remember(exams) {
        listOf("") + exams.flatMap { e -> e.subjects.map { it.subject } }.distinct()
    }
    var subject by remember { mutableStateOf(existing?.subject ?: "") }
    var target by remember { mutableStateOf(existing?.targetScore?.let { ScoreEngine.fmtScore(it) } ?: "") }
    var full by remember { mutableStateOf(existing?.targetFull?.let { ScoreEngine.fmtScore(it) } ?: "750") }
    var dateText by remember { mutableStateOf(existing?.examDate?.takeIf { it > 0 }?.let { Dates.fmt(it) } ?: "") }
    var note by remember { mutableStateOf(existing?.note ?: "") }
    var error by remember { mutableStateOf("") }

    OverlayDialog(
        show = true, title = if (existing == null) "设定目标" else "修改目标",
        summary = "目标只影响进度与建议 不改动成绩",
        onDismissRequest = onClose,
    ) {
        Column(Modifier.fillMaxWidth().heightIn(max = 440.dp).verticalScroll(rememberScrollState())) {
            Text("科目 留空为总分", fontSize = 11.sp, color = c.secondary)
            Spacer(Modifier.height(6.dp))
            LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                items(subjects) { s ->
                    Chip(s.ifBlank { "总分" }, s == subject) { subject = s }
                }
            }
            Spacer(Modifier.height(10.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Box(Modifier.weight(1f)) { SimpleField("目标分数", target, { target = it }) }
                Box(Modifier.weight(1f)) { SimpleField("满分", full, { full = it }) }
            }
            Spacer(Modifier.height(8.dp))
            SimpleField("考试日期 可空", dateText, { dateText = it })
            Spacer(Modifier.height(8.dp))
            SimpleField("备注", note, { note = it })
            if (error.isNotBlank()) {
                Spacer(Modifier.height(6.dp))
                Text(error, fontSize = 10.5.sp, color = c.negative)
            }
            Spacer(Modifier.height(12.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                SoftButton("取消", onClose, modifier = Modifier.weight(1f))
                PrimaryButton("保存", {
                    val t = target.toDoubleOrNull()
                    val f = full.toDoubleOrNull()
                    val date = if (dateText.isBlank()) 0L else parseDay(dateText)
                    if (t == null || f == null || f <= 0 || t < 0 || t > f) {
                        error = "目标分数需在 0 到满分之间"
                    } else {
                        onSave(
                            GoalEntity(
                                id = existing?.id ?: 0,
                                subject = subject,
                                targetScore = t,
                                targetFull = f,
                                targetRate = t / f,
                                examDate = date ?: 0L,
                                note = note,
                                createdAt = existing?.createdAt ?: System.currentTimeMillis(),
                                achieved = existing?.achieved ?: false,
                            )
                        )
                    }
                }, modifier = Modifier.weight(1f))
            }
        }
    }
}

